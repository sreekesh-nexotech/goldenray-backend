"""Render ``docs/postman/COVERAGE_REPORT.md`` from the machine artifacts (host python3, stdlib only).

    python3 docs/postman/_work/write_report.py

Inputs: inventory.json, resolver.json (excluded HEAD/OPTIONS), static_scan.json (dynamic constructs), coverage.json
(verify_coverage.py), fragments/*.json (unresolved notes) and ``report_notes.md`` (hand-written: verifier findings and
assumptions — the only non-generated part).
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

WORK = Path(__file__).resolve().parent
OUT = WORK.parent / "COVERAGE_REPORT.md"


def main():
    inventory = json.loads((WORK / "inventory.json").read_text())
    resolver = json.loads((WORK / "resolver.json").read_text())
    static = json.loads((WORK / "static_scan.json").read_text())
    coverage = json.loads((WORK / "coverage.json").read_text())
    frags = []
    for file in sorted((WORK / "fragments").glob("*.json")):
        frags += json.loads(file.read_text())
    notes = (WORK / "report_notes.md").read_text() if (WORK / "report_notes.md").exists() else ""

    surfaces = Counter(r["surface"] for r in inventory)
    methods = Counter(r["method"] for r in inventory)
    schema_rows = sum("schema" in r["source"] for r in inventory)
    refused = [r for r in inventory if r.get("refused")]
    redirects = [r for r in inventory if r["view"].endswith("AppendSlashView")]
    lines = [
        "# Postman collection: coverage report",
        "",
        "_Generated by `docs/postman/_work/write_report.py`. Regenerate it, don't edit it. Hand-written notes live in `_work/report_notes.md`._",
        "",
        "## Result",
        "",
        f"- **Inventory:** {len(inventory)} HTTP endpoints, one per unique (method, path).",
        f"- **Collection:** {coverage['collection_requests']} requests, covering {coverage['covered']} inventory endpoints.",
        f"- **Missing:** **{len(coverage['missing'])}**",
        f"- **Requests that match no endpoint:** **{len(coverage['extras'])}**",
        "",
        "`verify_coverage.py` reads the final collection JSON and compares it against `inventory.json`. It exits non-zero if anything is missing.",
        "",
        "## How the inventory was built (three independent sources)",
        "",
        "1. **Live URL resolver** (`dump_urls.py`, run inside the API container). It walks `get_resolver()` recursively through every include, namespace and router. "
        "Methods come from `callback.actions` for ViewSets (including `@action` routes), the handler methods for API views, and the methods a plain function view checks "
        f"for. Result: {len(resolver['rows'])} rows, {len(resolver['duplicates'])} duplicates.",
        f"2. **OpenAPI schema** from drf-spectacular (`manage.py spectacular --api-version v1`). {schema_rows} of its operations match resolver rows, and none of them are missing from the resolver.",
        "3. **Static scan** (`static_scan.py`). It greps for the URL-defining constructs and parses every `urls.py` and views module with `ast`. Every "
        f"`router.register`, `as_view`, literal `path()` and `@action` ({len(static['actions'])} actions) was confirmed in the resolver; {len(static['problems'])} "
        "problems. Dynamic constructs it found (resolved at runtime by source 1):",
    ]
    for d in static["dynamic_constructs"]:
        lines.append(f"   - `{d['file']}:{d['line']}`: {d['what']}")
    lines += [
        "",
        "",
        f"The schema leaves out {len(inventory) - schema_rows} endpoints. All of them are explained:",
        "- legacy / iclock / ops / dev-media views are excluded from the schema on purpose (`schema = None` or plain Django views): "
        f"{sum(1 for r in inventory if r['surface'] in ('legacy', 'iclock', 'ops', 'dev-media'))};",
        f"- methods that are routed but always refused: {len(refused)} (see below).",
        "",
        "## Counts",
        "",
        "| Surface | Endpoints |",
        "|---|---:|",
    ]
    lines += [f"| {s} | {n} |" for s, n in sorted(surfaces.items())]
    lines += ["", "| Method | Endpoints |", "|---|---:|"] + [f"| {m} | {n} |" for m, n in sorted(methods.items())]
    lines += ["", "| App | Endpoints | In collection |", "|---|---:|---:|"]
    lines += [f"| {app} | {v['inventory']} | {v['covered']} |" for app, v in coverage["per_app"].items()]
    lines += [
        "",
        "## Included, but worth knowing",
        "",
        f"- **Refused methods ({len(refused)}).** The DRF router maps these routes, but every caller gets refused. Most are `PUT …/{{uid}}/` on resources you edit with "
        "PATCH: `update` isn't in the view's `action_permissions`, so RBAC denies it with 403 (default deny), or `PatchOnlyUpdateMixin` answers 405. They are in the "
        "folder *12 Refused methods*, and each request asserts its 403 or 405.",
        f"- **Legacy slash-less redirects ({len(redirects)}).** `AppendSlashView` answers 301 to the slashed old URL on GET/POST/PUT/PATCH/DELETE. They are in *11 Legacy "
        "shim › slash-less redirects (301)*.",
        "- **Feature-flagged surfaces.** `/iclock/…` needs `ADMS_RECEIVER` and `/legacy/…` needs `LEGACY_API_SHIM`. Both are database flags checked at request time, so "
        "the routes are always registered but answer 404 while their flag is off.",
        "- **DEBUG-only route.** `GET /media/public/{path}` is mounted only when `DEBUG` is on and `MEDIA_PUBLIC_BACKEND=local`. It is in the folder *13 Ops & docs*.",
        "",
        "## Excluded (with reasons)",
        "",
        f"- **Automatic HEAD and OPTIONS handlers ({len(resolver['excluded_methods'])}).** DRF and Django answer these on every view (HEAD mirrors GET; OPTIONS returns "
        "metadata, which this project denies unless it is mapped). They aren't separate endpoints.",
        "- **Django admin.** None: `django.contrib.admin` isn't installed and no admin URLs are mounted.",
        "- **WebSockets / Channels.** None: Channels isn't installed and there is no ASGI routing. This is excluded by the engineering standard.",
        "- **Third-party URL includes.** None: auth is built in-house (`accounts`, on simplejwt classes, with no simplejwt URL views). `flarize/urls.py` mounts only the "
        "four versioned surfaces plus iclock, legacy, schema/docs, healthz and debug media.",
        "",
    ]
    unresolved = defaultdict(list)
    for f in frags:
        for u in f.get("unresolved") or []:
            unresolved[f["app"]].append(f"`{f['id']}`: {u}")
    lines += ["## Endpoints needing human review", ""]
    if unresolved:
        for app in sorted(unresolved):
            lines.append(f"**{app}**")
            lines += [f"- {u}" for u in unresolved[app]]
            lines.append("")
    else:
        lines += ["None of the fragments record an unresolved item.", ""]
    if notes:
        lines += [notes.strip(), ""]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
