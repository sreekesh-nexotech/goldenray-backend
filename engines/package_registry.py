def archive_package(registry: dict, *, actor: Any, package_id: Any, reason: Any, at: Any, authorize: Authorize = assert_can) -> dict:
    """ARCHIVED (PACKAGE_ARCHIVE); an active APPROVED record must be superseded or rejected first."""
    authorize(actor, CAPABILITY["PACKAGE_ARCHIVE"])
    _require_at(at)
    if not truthy(reason) or not js_trim(js_str(reason)):
        raise ApprovalError("A reason is required when archiving a package.", APPROVAL_ERROR["MISSING_REASON"], {"packageId": package_id})
    pkg = _find_package(registry, package_id)
    if pkg is None:
        raise _not_found(package_id)
    if pkg.get("packageState") == PACKAGE_STATE["APPROVED"] and not truthy(pkg.get("supersededBy")):
        raise ApprovalError(
            f'Package "{js_str(package_id)}" is an active APPROVED record and cannot be archived until it is superseded or rejected.',
            APPROVAL_ERROR["CANNOT_ARCHIVE_ACTIVE_APPROVED"],
            {"packageId": package_id},
        )
    pkg["packageState"] = PACKAGE_STATE["ARCHIVED"]
    pkg["archivedBy"] = _user_id(actor)
    pkg["archivedAt"] = at
    pkg["archivalReason"] = js_trim(js_str(reason))
    return clean({"packageId": package_id, "packageState": PACKAGE_STATE["ARCHIVED"], "archivedBy": _user_id(actor), "archivedAt": at})


def _checker_role(component: Any) -> str:
    if not truthy(component):
        return "OTHER"
    component_id = jsget(component, "componentId")
    if truthy(component_id) and component_id in _ENPHASE_COMPONENT_ROLES:
        return _ENPHASE_COMPONENT_ROLES[component_id]
    role = jsget(component, "role")
    if truthy(role) and role in _CATEGORY_TO_CHECKER_ROLE:
        return _CATEGORY_TO_CHECKER_ROLE[role]
    return "OTHER"


def run_package_checker(registry: dict, env: Any, *, actor: Any, package_id: Any, at: Any, check_project_bom: Callable[[dict], dict], authorize: Authorize = assert_can) -> dict:
    """Run the engineering checker at TEMPLATE scope and pin the result (with the revision) on ``lastValidation``.

    ``check_project_bom`` receives the JS argument object of ``engineeringChecker.checkProjectBom`` as one dict.
    """
    authorize(actor, CAPABILITY["BOM_RUN_CHECKER"])
    _require_at(at)
    pkg = _find_package(registry, package_id)
    if pkg is None:
        raise _not_found(package_id)
    architecture = pkg.get("architecture")
    if architecture is not None and architecture not in VALID_ARCHITECTURES:
        raise _architecture_invalid(architecture)
    env = env if isinstance(env, dict) else {}
    resolved = resolve_package_architecture(pkg, env.get("catalog"))
    if not resolved["architecture"]:
        raise ApprovalError(
            f'Package "{js_str(package_id)}" has no architecture declared and its profile "{js_str(jsget(pkg, "profileKey"))}" ' "declares no inverterType; the checker cannot run.",
            APPROVAL_ERROR["ARCHITECTURE_UNDECLARED"],
            {"packageId": package_id, "profileKey": nullish(jsget(pkg, "profileKey"), None)},
        )
    components = pkg.get("components") if is_array(pkg.get("components")) else []
    lines = [clean({"role": _checker_role(c), "componentId": jsget(c, "componentId"), "quantity": jsget(c, "quantity")}) for c in components]
    lines = _stable_sort(lines, lambda a, b: locale_compare(js_str(a["role"]), js_str(b["role"])))
    bom = {"phase": jsget(pkg, "phase"), "architecture": resolved["architecture"], "sysType": nullish(jsget(pkg, "systemType"), None), "lines": lines}
    validation = check_project_bom(
        {
            "bom": clean(bom),
            "lines": lines,
            "templateScope": True,
            "catalog": env.get("catalog") if truthy(env.get("catalog")) else {"categories": {}},
            "batteryMaster": env.get("batteryMaster") if truthy(env.get("batteryMaster")) else {},
            "at": at,
            "catalogVersion": nullish(env.get("catalogVersion"), None),
            "upgrade": None,
            "futureUpgrade": False,
        }
    )
    revision_number = pkg.get("revisionNumber") if truthy(pkg.get("revisionNumber")) else 1
    pkg["lastValidation"] = {**validation, "revisionNumber": revision_number, "architecture": resolved["architecture"], "architectureSource": resolved["source"]}
    return pkg["lastValidation"]


def _stable_sort(items: list, compare: Callable[[Any, Any], int]) -> list:
    return sorted(items, key=functools.cmp_to_key(compare))


