def create_revision(registry: dict, *, actor: Any, source_package_id: Any, at: Any, id_factory: Callable[[dict], str] | None = None, authorize: Authorize = assert_can) -> dict:
    """A DRAFT revision (revisionNumber + 1, same comboKey) of an APPROVED, non-superseded package (PACKAGE_EDIT)."""
    authorize(actor, CAPABILITY["PACKAGE_EDIT"])
    _require_at(at)
    source = _find_package(registry, source_package_id)
    if source is None:
        raise _not_found(source_package_id)
    if source.get("packageState") != PACKAGE_STATE["APPROVED"] or truthy(source.get("supersededBy")):
        raise ApprovalError(
            f'Cannot revise "{js_str(source_package_id)}" — it is not an APPROVED, non-superseded record.',
            APPROVAL_ERROR["NOT_APPROVED_SOURCE"],
            clean({"packageId": source_package_id, "packageState": jsget(source, "packageState"), "supersededBy": jsget(source, "supersededBy")}),
        )
    revision = copy.deepcopy(source)
    package_id = (id_factory or _DEFAULT_ID_FACTORY)(source)
    revision["packageId"] = package_id
    revision_number = source.get("revisionNumber")
    revision["revisionNumber"] = (revision_number if truthy(revision_number) else 1) + 1
    combo = source.get("comboKey")
    revision["comboKey"] = combo if not is_nullish(combo) else "|".join(js_str(nullish(source.get(k), "")) for k in ("systemType", "size", "phase", "tier"))
    revision["packageState"] = PACKAGE_STATE["DRAFT"]
    revision["supersededBy"] = None
    revision.update(_RESET_ON_COPY)
    revision["createdBy"] = _user_id(actor)
    revision["createdAt"] = at
    revision["architecture"] = nullish(source.get("architecture"), None)
    revision = clean(revision)
    registry["packages"].append(revision)
    return {"packageId": package_id, "package": revision}


def edit_package(registry: dict, *, actor: Any, package_id: Any, patch: Any, at: Any, authorize: Authorize = assert_can) -> dict:
    """Patch ``architecture`` / ``components`` / ``profileKey`` of a DRAFT; any edit clears the validation."""
    authorize(actor, CAPABILITY["PACKAGE_EDIT"])
    _require_at(at)
    pkg = _find_package(registry, package_id)
    if pkg is None:
        raise _not_found(package_id)
    if pkg.get("packageState") != PACKAGE_STATE["DRAFT"]:
        raise ApprovalError(
            f'Package "{js_str(package_id)}" is {js_str(jsget(pkg, "packageState"))}; only DRAFT packages may be edited.',
            APPROVAL_ERROR["NOT_DRAFT_STATE"],
            clean({"packageId": package_id, "packageState": jsget(pkg, "packageState")}),
        )
    changes = patch if truthy(patch) and is_object(patch) else {}
    for key in js_keys(changes):
        if key not in EDITABLE_FIELDS:
            raise ApprovalError(f'Field "{key}" is not editable on a DRAFT package.', "IMMUTABLE_FIELD", {"field": key})
    if isinstance(changes, dict):
        if "architecture" in changes:
            if changes["architecture"] not in VALID_ARCHITECTURES:
                raise _architecture_invalid(changes["architecture"])
            pkg["architecture"] = changes["architecture"]
        if "components" in changes:
            if not is_array(changes["components"]):
                raise ApprovalError("components must be an array.", "IMMUTABLE_FIELD", {"field": "components"})
            pkg["components"] = copy.deepcopy(changes["components"])
        if "profileKey" in changes:
            pkg["profileKey"] = changes["profileKey"]
    pkg["lastValidation"] = None
    return {"packageId": package_id, "package": pkg}


def submit_package(registry: dict, *, actor: Any, package_id: Any, at: Any, acknowledge_warnings: bool = False, authorize: Authorize = assert_can) -> dict:
    """DRAFT → SUBMITTED (PACKAGE_SUBMIT) behind the same validation gate as approval."""
    authorize(actor, CAPABILITY["PACKAGE_SUBMIT"])
    _require_at(at)
    pkg = _find_package(registry, package_id)
    if pkg is None:
        raise _not_found(package_id)
