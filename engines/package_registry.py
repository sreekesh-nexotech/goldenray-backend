"""Package registry lifecycle — ports of Flarize ``packageApproval.js`` (V4), ``packageAuthority.js`` and
``packageProjection.js``.

A registry is ``{"schema", "packages": [...]}``. A package moves DRAFT → SUBMITTED → APPROVED (or REJECTED); approving
a revision supersedes the previous APPROVED revision of the same ``comboKey``; only a superseded or non-approved
record may be ARCHIVED. Approval needs a fresh VALID engineering validation of the current revision.

Like the JS, the lifecycle functions MUTATE the registry passed in and return a small result dict. Engineering
validation (``runPackageChecker``) calls the engineering checker through an injected ``check_project_bom`` callable
(the checker is its own engine). Package ids are generated by an injectable :class:`PackageIdFactory` (the JS used
``Date.now()`` and an in-process counter).
"""

